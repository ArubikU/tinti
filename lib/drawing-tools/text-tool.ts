  getPreview() {
    if (!this.startPoint) return {}

    const pixels = this.renderText(this.startPoint)
    const preview: { [key: string]: string } = {}
    pixels.forEach((p) => {
      if (p.color) preview[`${p.x},${p.y}`] = p.color
    })
    return preview
  }

  private renderText(start: Point) {
    const pixels: { x: number; y: number; color: string | null }[] = []

    // Simple bitmap font rendering (8x8 pixels per character)
    const charWidth = Math.max(4, Math.floor(this.fontSize / 2))
    const charHeight = this.fontSize

    for (let i = 0; i < this.text.length; i++) {
      const char = this.text[i]
      const charX = start.x + i * (charWidth + 1)

      // Simple character patterns (very basic)
      const pattern = this.getCharPattern(char, charWidth, charHeight)

      for (let y = 0; y < charHeight; y++) {
        for (let x = 0; x < charWidth; x++) {
          if (pattern[y] && pattern[y][x]) {
            pixels.push({ x: charX + x, y: start.y + y, color: this.color })
          }
        }
      }
    }

    return pixels
  }

